test('auditor cannot submit or mutate',async({page})=>{
 await login(page,auditor)
 await expect(page.getByRole('button',{name:'New claim',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:/^Open claim SC-/}).first().click()
 await expect(page.getByText('Read-only audit access.')).toBeVisible()
 await expect(page.getByLabel('Review reason')).toHaveCount(0)
})
test('API failure stays visible and retry restores queue',async({page})=>{
 await page.route('**/api/v1/claims',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Simulated temporary API failure'})}))
 await login(page)
 await expect(page.getByRole('alert')).toContainText('Simulated temporary API failure')
 await page.unroute('**/api/v1/claims')
 await page.getByRole('button',{name:'Retry',exact:true}).click()
 await expect(page.getByRole('alert')).toHaveCount(0)
 await expect(page.getByRole('button',{name:/^Open claim SC-/}).first()).toBeVisible()
})
