import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'
const root=path.resolve(import.meta.dirname,'../../..')
const identities=JSON.parse(fs.readFileSync(process.env.DEMO_IDENTITIES_FILE || path.join(root,'work/demo-identities.json'),'utf8')) as Record<string,{subject:string;role:string}>
const token=Object.keys(identities).find(t=>identities[t].subject==='demo-adjuster')!
const auditor=Object.keys(identities).find(t=>identities[t].subject==='demo-auditor')!
const evidence=path.join(root,'work/screenshots')
async function login(page:import('@playwright/test').Page,value=token){await page.goto('/');await page.getByLabel('Synthetic session token').fill(value);await page.getByRole('button',{name:'Open workspace'}).click();await expect(page.getByRole('heading',{name:'Claims command center'})).toBeVisible();await expect(page.getByRole('status').filter({hasText:'Loading'})).toHaveCount(0)}
test('dashboard, persistent FNOL, human transition and timeline',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await login(page)
 fs.mkdirSync(evidence,{recursive:true})
 await page.screenshot({path:path.join(evidence,'dashboard-desktop.png'),fullPage:true})
 await page.getByRole('button',{name:'New claim',exact:true}).click()
 await page.getByLabel('Policyholder name').fill('Browser Fiction '+Date.now())
 const name=await page.getByLabel('Policyholder name').inputValue()
 await page.getByLabel('Policy reference', {exact:true}).fill('SYN-BROWSER-01')
 await page.getByLabel('Vehicle',{exact:true}).fill('2024 Honda Civic')
 await page.getByLabel('VIN',{exact:true}).fill('1HGCM82633A004352')
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByLabel('Incident date',{exact:true}).fill('2026-10-01')
 await page.getByLabel('Incident location').fill('Fictional Harbor Avenue')
 await page.getByLabel('Damage description').fill('Browser acceptance: synthetic bumper damage in a fictional parking lot.')
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Review your claim'})).toBeVisible()
 await page.screenshot({path:path.join(evidence,'fnol-review.png'),fullPage:true})
 await page.getByRole('button',{name:'Submit synthetic FNOL'}).click()
 await expect(page.getByRole('status').filter({hasText:'Claim submitted successfully'})).toContainText('Claim submitted successfully')
 await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
 await expect(page.getByText('Synthetic FNOL submitted',{exact:true})).toBeVisible()
 await page.getByLabel('Review reason').fill('Synthetic intake verified by browser test')
 await page.getByRole('button',{name:'Move to triage',exact:true}).click()
 await expect(page.getByText('Synthetic intake verified by browser test',{exact:true})).toBeVisible()
 await page.screenshot({path:path.join(evidence,'claim-timeline.png'),fullPage:true})
 await page.reload()
 await expect(page.getByLabel('Synthetic session token')).toBeVisible()
 await page.getByLabel('Synthetic session token').fill(token)
 await page.getByRole('button',{name:'Open workspace'}).click()
 await page.getByRole('searchbox',{name:'Search claims'}).fill(name)
 await expect(page.getByRole('button',{name:/^Open claim SC-/})).toHaveCount(1)
 await page.getByRole('button',{name:/^Open claim SC-/}).click()
 await expect(page.getByText('Synthetic intake verified by browser test',{exact:true})).toBeVisible()
 expect(errors).toEqual([])
})
